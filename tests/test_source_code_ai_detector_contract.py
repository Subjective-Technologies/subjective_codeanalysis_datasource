# --------------------------------------------------------------------------
# 13. Empty source behavior
# --------------------------------------------------------------------------
def test_empty_source():
    result = SourceCodeAIDetector.validate("")
    assert_result_contract(result)
    assert result["ai_likelihood"] == 0.0
    assert result["label"] == "low_ai_evidence"
    assert result["evidence"] == []


# --------------------------------------------------------------------------
# 14. Binary / unreadable file path behavior
#
# Chosen behavior: return a safe low-evidence result with an explanatory
# evidence note rather than raising.
# --------------------------------------------------------------------------
def test_binary_file_safe_result(tmp_path):
    path = tmp_path / "blob.bin"
    path.write_bytes(b"\x00\x01\x02\xff\xfe\xfd" * 64)

    result = SourceCodeAIDetector.validate(str(path))
    assert_result_contract(result)

    assert result["input_type"] == "path"
    assert result["ai_likelihood"] == 0.0
    assert any("decode" in e.lower() for e in result["evidence"])


# --------------------------------------------------------------------------
# 15. Deterministic output
# --------------------------------------------------------------------------
def test_deterministic_output():
    source = read_fixture("mixed_samples", "contaminated_config.py")
    first = SourceCodeAIDetector.validate(source)
    second = SourceCodeAIDetector.validate(source)

    assert first["ai_likelihood"] == second["ai_likelihood"]
    assert first["label"] == second["label"]
    assert detector_ids(first) == detector_ids(second)
